// The crisis path.
//
// Until now, if somebody wrote that they wanted to hurt themselves, nothing
// happened. That was the honest answer and the worst thing about the product.
//
// WHY THERE IS NO DETECTION HERE
//
// The obvious build is a keyword list that watches what people type. We are
// deliberately not doing that, and it is the most important decision in this
// file.
//
// A keyword detector on free text about painful thoughts is wrong in both
// directions at once. It misses almost everything that matters — people in
// real distress rarely announce it in the vocabulary a word list expects —
// and it fires on ordinary sentences, so a person writing about a hard day
// gets an emergency banner they did not ask for. The combination is worse
// than nothing: it looks like a safety net, so it earns trust it cannot
// repay, and the first person it fails is the one it was built for.
//
// It is also surveillance of the one thing we promised not to read closely.
//
// So the route is ALWAYS THERE INSTEAD. Quiet, permanent, one tap from
// anywhere, never triggered and never withheld. Nobody has to be classified
// as being in crisis to reach it, which means nobody has to be classified
// wrongly. An always-open door needs no detector.
//
// WHAT THIS IS NOT
//
// Aether is not therapy, not treatment and not a clinician, and the panel
// says so in those words. We have no clinical trial and do not claim one.
// The mechanisms the product is built on have published evidence; the
// product does not. That distinction is not pedantry — it is the difference
// between an honest claim and a medical one.
//
// ON THE NUMBERS
//
// Verified against multiple independent sources rather than written from
// memory, because a wrong helpline number does real harm to a real person at
// the worst moment of their day.
//
// Tele-MANAS (14416) is the strongest: run by India's Ministry of Health and
// Family Welfare, 24x7, multi-language, and listed on government medical
// institute pages. It is therefore shown first.
//
// KIRAN is listed by most sources as 1800-599-0019, but one page gives
// 1800-500-0019. The majority and that page's own process description agree
// on 599, so that is what ships — and it is second, behind the number we are
// most sure of. Anyone maintaining this file should re-check both against the
// ministry's own site before a public launch, and should treat any number
// they cannot confirm as a reason to remove it rather than to guess.

